create or replace function public.frota_versao_operador() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 if NEW.uid is distinct from OLD.uid or NEW.ativo is distinct from OLD.ativo then
  update public.equipamentos set config_versao=config_versao+1
  where id_equipamento in(select equipamento_id from public.operador_equipamento where operador_id=NEW.id_operador);
 end if;
 return NEW;
end $$;
drop trigger if exists frota_versao_operador on public.operadores;
create trigger frota_versao_operador after update on public.operadores
 for each row execute function public.frota_versao_operador();

create or replace function public.frota_validar_vinculo() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 if TG_OP='UPDATE' and (NEW.equipamento_id<>OLD.equipamento_id or NEW.operador_id<>OLD.operador_id) then
  raise exception 'Identidade do vinculo e imutavel' using errcode='23514';
 end if;
 if not exists(select 1 from public.equipamentos e join public.operadores o
  on o.fk_fazenda_id_fazenda=e.fk_fazenda_id_fazenda
  where e.id_equipamento=NEW.equipamento_id and o.id_operador=NEW.operador_id) then
  raise exception 'Operador e equipamento devem pertencer a mesma fazenda' using errcode='23514';
 end if;
 if TG_OP='INSERT' or NEW.ativo is distinct from OLD.ativo then
  update public.equipamentos set config_versao=config_versao+1 where id_equipamento=NEW.equipamento_id;
 end if;
 return NEW;
end $$;
